/** Własny tekst tematu: `second` = odpowiednik klucza `*NAZWA2`. */
export function ownCivilopediaText(type: number, name: string, second: boolean): string | null {
  const entry = CIVILOPEDIA_TEXT[type]?.[name.toUpperCase()];
  const text = second ? entry?.text2 : entry?.text;
  return text ?? null;
}
